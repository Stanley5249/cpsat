//! Rust binding for the OR-Tools CP-SAT solver.
//!
//! Models, parameters, and responses are the Buffa types in [`proto`], so every
//! schema field is available and a model stays plain, mutable data between
//! solves. The solver runs in native OR-Tools behind a small C ABI.
//!
//! ```no_run
//! use cpsat::proto::{CpModelProto, IntegerVariableProto, SatParameters};
//!
//! let model = CpModelProto {
//!     variables: vec![IntegerVariableProto {
//!         domain: vec![0, 10],
//!         ..Default::default()
//!     }],
//!     ..Default::default()
//! };
//! let params = SatParameters {
//!     num_workers: Some(8),
//!     ..Default::default()
//! };
//! let response = cpsat::solve(&model, &params)?;
//! # anyhow::Ok(())
//! ```
//!
//! [`solve_with`] adds solution, best-bound, and log events, and a
//! [`StopHandle`] stops a solve from any thread.
//!
//! OR-Tools aborts the process on an internal `CHECK` failure, which Rust
//! cannot catch. [`validate`] reports invalid models without solving.

mod diagnostics;
mod native;
#[expect(
    clippy::all,
    clippy::pedantic,
    clippy::allow_attributes,
    clippy::allow_attributes_without_reason,
    reason = "generated by buffa, which follows its own lint policy"
)]
pub mod proto;
mod solve;

/// The Protobuf runtime, re-exported so callers use the same `Message` trait.
pub use buffa;
pub use diagnostics::{model_stats, response_stats, validate};
pub use solve::{Event, Events, StopHandle, solve, solve_with};
